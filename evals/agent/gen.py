"""Render suite.yaml and fake-rules.json from cases.py (stdlib only).

    python evals/agent/gen.py                 # write both files
    python evals/agent/gen.py --check         # fail if either file is stale
    python evals/agent/gen.py --dry-run-tools --corpus <dir> [--codegraph <exe>]
        # execute every scripted tool call through the proxy's tool layer and report
        # errors + output sizes (catches scripts that drifted from the corpus)

fake_llm (evalrig/scripts/fake_llm.py) matches `match` regexes against the whole
prompt: every message's content joined with newlines. The proxy prefixes each tool
result with `[tool NAME]`, so "turn k of question Qnn" is the rule whose regex needs at
least c_k tool-result markers after `[Qnn]`, where c_k is the number of calls scripted
before turn k. Rules are emitted most-advanced first (first match wins).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from cases import ARMS, CASES  # noqa: E402

SUITE = HERE / "suite.yaml"
RULES = HERE / "fake-rules.json"

HEADER = """\
# GENERATED by evals/agent/gen.py from evals/agent/cases.py - edit cases.py, then run
#   python evals/agent/gen.py
# Agent eval: the same code questions answered by an agent with grep-only tools vs
# codegraph tools. `cgagent` is the agent proxy (evals/agent/proxy.py), an
# openai-compatible provider whose models are the two arms. Every expected answer was
# verified against SCIP ground truth or by reading the source (see cases.py `truth`).
"""


def q(s: str) -> str:
    """YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(s, ensure_ascii=False)


def render_suite() -> str:
    out = [HEADER]
    out.append("name: codegraph-agent\n")
    out.append(
        "description: >\n  Code-navigation questions over the pinned codegraph accuracy corpus\n"
        "  (Go/Rust/TypeScript/Python), answered by an agent loop with grep-only tools\n"
        "  vs codegraph tools. Compare pass rate and total tokens per arm.\n\n"
    )
    out.append(
        "prompt:\n  template: |\n    [{{ qid }}] {{ question }}\n\n"
        "    Answer with a short list of names (one per line), nothing else.\n\n"
    )
    out.append("models:\n  - cgagent:grep\n  - cgagent:codegraph\n\n")
    out.append("params:\n  temperature: 0\n  max_tokens: 1024\n\n")
    out.append("threshold: 1.0\n\n")
    out.append("dataset:\n  cases:\n")
    for c in CASES:
        out.append(f"    - id: {c['id']}\n")
        out.append(f"      tags: [{c['lang']}, {c['repo']}, {c['kind']}]\n")
        out.append(f"      vars:\n        qid: {c['id']}\n        question: {q(c['question'])}\n")
        vals = ", ".join(q(v) for v in c["expect"])
        out.append("      graders:\n")
        out.append(f"        - {{type: contains, mode: all, value: [{vals}]}}\n")
    return "".join(out)


def marker_regex(qid: str, n: int) -> str:
    base = rf"\[{qid}\]"
    return rf"(?s){base}(?:.*?\[tool \w+\]){{{n}}}" if n else base


def render_rules() -> str:
    rules: list[dict[str, object]] = []
    for c in CASES:
        for arm in ARMS:
            steps = c[arm]
            counts = [0]
            for step in steps:
                counts.append(counts[-1] + len(step))
            rules.append({"model": f"fake-{arm}", "match": marker_regex(c["id"], counts[-1]), "reply": c["answer"]})
            for k in range(len(steps) - 1, -1, -1):
                rules.append(
                    {
                        "model": f"fake-{arm}",
                        "match": marker_regex(c["id"], counts[k]),
                        "tool_calls": [{"name": n, "arguments": a} for n, a in steps[k]],
                    }
                )
    spec = {
        "_comment": "GENERATED by evals/agent/gen.py from cases.py. Scripted agent turns for "
        "evalrig's fake_llm; the final replies are the verified answers for BOTH arms.",
        "default": "I don't know.",
        "rules": rules,
    }
    return json.dumps(spec, indent=1, ensure_ascii=False) + "\n"


def dry_run(corpus: str, codegraph: str, state: str) -> int:
    import proxy

    corp = proxy.Corpus(Path(corpus))
    settings = proxy.Settings(corpus=corp)
    env = proxy.kit_env(Path(state))
    mcp = proxy.McpClient(Path(codegraph), corp.root, env)
    arms = proxy.build_arms(settings, mcp)
    bad = 0
    try:
        for c in CASES:
            for arm in ARMS:
                sizes = []
                for step in c[arm]:
                    for name, args in step:
                        try:
                            out = proxy.run_tool(settings, mcp, arms[arm], name, args)
                            flag = (" TRUNC" if "[truncated:" in out else "") + (
                                " CAP" if "[per-file cap:" in out else ""
                            )
                            sizes.append(f"{name}={len(out)}{flag}")
                            if out in ("no matches", "no files") or out.startswith("no symbols"):
                                bad += 1
                                sizes[-1] += " EMPTY"
                        except proxy.ToolError as exc:
                            bad += 1
                            sizes.append(f"{name}=ERROR({exc})")
                print(f"{c['id']} {arm:9} {' '.join(sizes)}")
    finally:
        mcp.close()
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dry-run-tools", action="store_true")
    ap.add_argument("--corpus")
    ap.add_argument("--codegraph", default=str(HERE.parent.parent / "target" / "release" / "codegraph.exe"))
    ap.add_argument("--state-dir", default=str(HERE.parent.parent / ".cache" / "evals"))
    args = ap.parse_args()
    if args.dry_run_tools:
        if not args.corpus:
            ap.error("--dry-run-tools needs --corpus")
        return dry_run(args.corpus, args.codegraph, args.state_dir)
    want = {SUITE: render_suite(), RULES: render_rules()}
    if args.check:
        stale = [p.name for p, text in want.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print(f"stale: {', '.join(stale)} (run python evals/agent/gen.py)", file=sys.stderr)
            return 1
        return 0
    for p, text in want.items():
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(HERE.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
